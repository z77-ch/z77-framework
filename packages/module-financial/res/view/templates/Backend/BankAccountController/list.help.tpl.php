<h3>Bankkonten</h3>
<p>Die <strong>Bankkonten</strong> sagen, welche IBAN welches Konto der Buchhaltung ist — an einer einzigen Stelle. Zahlungsarten, die über eine Bank zahlen, verweisen darauf.</p>
<ul>
    <li><strong>+ Bankkonto</strong> legt eines an; das Zeichen am Zeilenanfang öffnet eines zum Bearbeiten.</li>
    <li><strong>Kontoauszug</strong> — «nein»: das Konto ist nur Stamm. «ja» oder «bis …»: Kontoauszüge können eingelesen werden, und bis zu diesem Datum sind sie es (Finanzen › Bankkonto). Geschaltet wird im Fenster.</li>
    <li><strong>Aktiv</strong> — ein inaktives Bankkonto nimmt keinen Kontoauszug mehr an. Gelöscht wird ein Bankkonto nie.</li>
    <li>Nur Konten in der Währung der Buchhaltung. Fremdwährungskonten folgen später.</li>
</ul>
