<h3>Belegvorlagen</h3>
<p>Die <strong>Belegvorlagen</strong> sind die Kacheln, die das Handy beim Erfassen eines Belegs zeigt — in der Reihenfolge dieser Liste. Jede Vorlage sagt, was gekauft wurde: Soll-Konto und MWST-Code. Wie bezahlt wurde (das Haben-Konto) kommt aus den Zahlungsarten.</p>
<ul>
    <li><strong>+ Vorlage</strong> legt eine neue Kachel an; das Zeichen am Zeilenanfang öffnet eine Vorlage zum Bearbeiten.</li>
    <li><strong>Aktiv</strong> — nur aktive Vorlagen erscheinen auf dem Handy. Ausgeschaltet verschwindet die Kachel; Belege, die sie schon tragen, behalten sie.</li>
    <li><strong>Belege</strong> zählt, wie viele Belege die Vorlage tragen. Gelöscht wird eine Vorlage nie — nur deaktiviert.</li>
</ul>
